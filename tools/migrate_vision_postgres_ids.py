"""Repair the three M71 PostgreSQL IDs; retain data and existing generators."""
import json

from sqlalchemy import text

TABLES = ("scene_lights", "scene_walls", "fog_of_war_state")


def migrate(connection):
    if connection.dialect.name != "postgresql":
        raise RuntimeError("This migration requires PostgreSQL.")
    connection.execute(text("SET LOCAL lock_timeout = '3s'"))
    connection.execute(text("SET LOCAL statement_timeout = '30s'"))
    connection.execute(text("LOCK TABLE " + ", ".join("public." + t for t in TABLES) + " IN ACCESS EXCLUSIVE MODE"))
    result = []
    for table in TABLES:
        column = connection.execute(text("""SELECT data_type, column_default, is_identity
            FROM information_schema.columns
            WHERE table_schema='public' AND table_name=:table AND column_name='id'"""), {"table": table}).mappings().one()
        key = connection.execute(text("""SELECT array_agg(a.attname ORDER BY k.ordinality)
            FROM pg_constraint c
            CROSS JOIN LATERAL unnest(c.conkey) WITH ORDINALITY k(attnum,ordinality)
            JOIN pg_attribute a ON a.attrelid=c.conrelid AND a.attnum=k.attnum
            WHERE c.conrelid=to_regclass(:table) AND c.contype='p'"""), {"table": "public." + table}).scalar()
        if column["data_type"] != "integer" or key != ["id"]:
            raise RuntimeError("Unexpected primary key: " + table)
        before = dict(connection.execute(text(f"SELECT count(*) AS rows, max(id) AS maximum FROM public.{table}")).mappings().one())
        sequence = connection.execute(text("SELECT pg_get_serial_sequence(:table,'id')"), {"table": "public." + table}).scalar()
        generated = column["is_identity"] == "YES" or bool(sequence and (column["column_default"] or "").startswith("nextval("))
        added = False
        if not generated:
            if column["column_default"] is not None or sequence is not None:
                raise RuntimeError("Unexpected existing ID default: " + table)
            start = max(1, (before["maximum"] or 0) + 1)
            if start > 2147483647:
                raise RuntimeError("Integer ID space exhausted: " + table)
            connection.execute(text(f"ALTER TABLE public.{table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH {start})"))
            added = True
        after = dict(connection.execute(text(f"SELECT count(*) AS rows, max(id) AS maximum FROM public.{table}")).mappings().one())
        if before != after:
            raise RuntimeError("Existing rows changed: " + table)
        actual_sequence = connection.execute(text("SELECT pg_get_serial_sequence(:table,'id')"), {"table": "public." + table}).scalar()
        if not actual_sequence:
            raise RuntimeError("ID generator missing after repair: " + table)
        result.append({"table": table, "identity_added": added, "before": before, "after": after, "sequence": actual_sequence})
    return {"status": "pass", "tables": result}


if __name__ == "__main__":
    import warnings
    warnings.filterwarnings("ignore")
    from vtt import create_app
    from vtt.extensions import db
    app = create_app("production")
    with app.app_context(), db.engine.begin() as connection:
        result = migrate(connection)
    print(json.dumps(result))
